"""Build the packaged RxNorm drug classes from the curated spec, using RxNav (ADR 0009).

Usage: uv run python scripts/build_drug_classes.py

For each ingredient name in scripts/drug_class_spec.toml the script:

* finds its RxCUI by exact name (RxNav ``rxcui.json?name=...&search=0``);
* checks the concept is an active ingredient (TTY ``IN``, not suppressed) whose RxNorm name
  equals the curated name; anything else stops the build;
* lists the active product concepts that contain it (``related.json`` for PRODUCT_TTYS);
* writes src/adhd_mcp/data/drug_classes/<id>.toml with per-ingredient provenance.

Retired product codes are not returned by RxNav and so are not matched (ADR 0009).
"""

import datetime as dt
import json
import tomllib
import urllib.parse
import urllib.request
from collections.abc import Callable
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "scripts" / "drug_class_spec.toml"
OUT = ROOT / "src" / "adhd_mcp" / "data" / "drug_classes"
RXNAV = "https://rxnav.nlm.nih.gov/REST"
PRODUCT_TTYS = (
    "PIN", "MIN", "SCDC", "SCDF", "SCDG", "SCD", "SBDC", "SBDF", "SBDG", "SBD", "GPCK", "BPCK"
)  # fmt: skip
CHECKED_BY = "Claude Code agent, delegated by the project owner on 2026-11-26"
CLASS_VERSION = "0.1.0"

Fetch = Callable[[str], Any]


def fetch_json(path: str) -> Any:  # pragma: no cover - network
    with urllib.request.urlopen(f"{RXNAV}/{path}", timeout=60) as response:  # noqa: S310
        return json.load(response)


class BuildError(Exception):
    pass


def ingredient(name: str, fetch: Fetch) -> tuple[str, list[str]]:
    """The verified RxCUI of an ingredient name and its sorted product RxCUIs."""
    ids = fetch(f"rxcui.json?name={urllib.parse.quote(name)}&search=0")["idGroup"]
    found = ids.get("rxnormId") or []
    if len(found) != 1:
        raise BuildError(f"{name}: expected one RxCUI, got {found}")
    rxcui = found[0]
    props = fetch(f"rxcui/{rxcui}/properties.json")["properties"]
    if props["tty"] != "IN" or props["suppress"] != "N" or props["name"].lower() != name:
        raise BuildError(f"{name}: RxCUI {rxcui} is {props['tty']} {props['name']!r}")
    related = fetch(f"rxcui/{rxcui}/related.json?tty={'+'.join(PRODUCT_TTYS)}")
    products = {
        c["rxcui"]
        for group in related["relatedGroup"].get("conceptGroup") or []
        for c in group.get("conceptProperties") or []
    }
    return rxcui, sorted(products, key=int)


def _quote(text: str) -> str:
    return json.dumps(text)


def render(spec: dict[str, Any], fetch: Fetch, rxnorm_version: str, today: dt.date) -> str:
    lines = [
        "# Generated by scripts/build_drug_classes.py from scripts/drug_class_spec.toml.",
        "# Do not edit by hand: change the spec and rebuild.",
        f"id = {_quote(spec['id'])}",
        f'version = "{CLASS_VERSION}"',
        f"title = {_quote(spec['title'])}",
    ]
    source = (
        "NLM RxNav REST API (rxnav.nlm.nih.gov): exact-name lookup, TTY IN and not suppressed; "
        "products from related.json"
    )
    for name in spec["ingredients"]:
        rxcui, products = ingredient(name, fetch)
        lines += [
            "",
            "[[ingredients]]",
            f'rxcui = "{rxcui}"',
            f"name = {_quote(name)}",
            "verified = true",
            f"source = {_quote(source)}",
            f"source_version = {_quote('RxNorm ' + rxnorm_version)}",
            f'checked_on = "{today.isoformat()}"',
            f"checked_by = {_quote(CHECKED_BY)}",
            "products = [",
            *(f'  "{p}",' for p in products),
            "]",
        ]
    return "\n".join(lines) + "\n"


def build(fetch: Fetch, out: Path, today: dt.date) -> list[Path]:
    spec = tomllib.loads(SPEC.read_text(encoding="utf-8"))
    rxnorm_version = fetch("version.json")["version"]
    written = []
    for class_spec in spec["classes"]:
        path = out / f"{class_spec['id']}.toml"
        path.write_text(render(class_spec, fetch, rxnorm_version, today), encoding="utf-8")
        written.append(path)
    return written


def main() -> None:  # pragma: no cover - network
    for path in build(fetch_json, OUT, dt.date.today()):  # noqa: DTZ011
        print(path.relative_to(ROOT))


if __name__ == "__main__":  # pragma: no cover
    main()
